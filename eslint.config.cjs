// The lint gate: `npm run lint` locally, in the commit hook and in CI. It is a .cjs file so that `require` finds the plugins in
// node_modules whatever the loader of the file that asks for them.
//
// Each rule is here to make the careless way of writing code the one that fails. There are no per-file allowlists and no
// disable comments (they are themselves an error): a rule that is wrong changes here, with its reason beside it, and what
// it flags is fixed in the code. The two exceptions below name one module or one function each, and say why.
const fs = require('node:fs')
const path = require('node:path')
const tseslint = require('typescript-eslint')
const comments = require('@eslint-community/eslint-plugin-eslint-comments')
const local = require('./tools/eslint_rules.cjs')

// The core: files that run on plain data, listed once, in tsconfig.core.json's "include". That file carries comments,
// which TypeScript allows and JSON does not, so they are stripped before it is read.
const tsconfig = JSON.parse(fs.readFileSync(path.join(__dirname, 'tsconfig.core.json'), 'utf8').replace(/^\s*\/\/.*$/gm, ''))
const CORE = tsconfig.include.filter(file => /\.tsx?$/.test(file) && !file.endsWith('.d.ts'))
const CORE_NAMES = CORE.map(file => path.basename(file, '.ts').replaceAll('.', '\\.')).join('|')

// Generated by tools/gitlab_schema.ts and checked there (`types --check`); a rule on it would only be fought by the generator.
const GENERATED = ['hooks/gitlab.generated.ts']

const PROBE = ['tools/store-probe/**/*.{ts,tsx}']
// The dev tools Node runs as they are: tools/*.ts, checked against tsconfig.tools.json.
const TOOLS = ['tools/*.ts']
const SOURCE = ['hooks/**/*.{ts,tsx}', 'tests/**/*.{ts,tsx}', 'tools/screens/**/*.{ts,tsx}', ...PROBE, ...TOOLS]

// The type-aware rules, which need the type-checker. The core is checked by tsconfig.core.json, which has no engine types and
// so keeps the layering honest; everything else by tsconfig.json, with the declarations of the Claude Code that CI pins
// (tools/engine_types.ts lays them out). Both get the same rules.
const TYPE_AWARE = {
  '@typescript-eslint/switch-exhaustiveness-check': 'error',
  '@typescript-eslint/no-floating-promises': 'error',
  '@typescript-eslint/no-unnecessary-condition': 'error',
  // A string, a number or a nullable one is not a condition: `''` and `0` are values, and `if (count)` is where a count
  // of zero goes missing. Say what is meant: `!== ''`, `> 0`, `!== null`.
  '@typescript-eslint/strict-boolean-expressions': [
    'error',
    {
      allowString: false,
      allowNumber: false,
      allowNullableObject: false,
      allowNullableBoolean: false,
      allowNullableString: false,
      allowNullableNumber: false,
      allowNullableEnum: false,
      allowAny: false,
    },
  ],
  '@typescript-eslint/no-unsafe-assignment': 'error',
  '@typescript-eslint/no-unsafe-call': 'error',
  '@typescript-eslint/no-unsafe-member-access': 'error',
  '@typescript-eslint/no-unsafe-return': 'error',
  '@typescript-eslint/no-unsafe-argument': 'error',
  '@typescript-eslint/prefer-readonly': 'error',
}

const tooling = { plugins: { '@typescript-eslint': tseslint.plugin, '@eslint-community/eslint-comments': comments, local } }

module.exports = [
  { ignores: ['types/**', '.claude/**', 'node_modules/**', ...GENERATED] },
  {
    files: SOURCE,
    languageOptions: { parser: tseslint.parser, sourceType: 'module' },
    linterOptions: { reportUnusedDisableDirectives: 'error' },
    ...tooling,
    rules: {
      // Nothing is switched off by comment: the config is the only place a rule changes.
      '@eslint-community/eslint-comments/no-use': ['error', { allow: [] }],
      '@typescript-eslint/ban-ts-comment': ['error', { 'ts-ignore': true, 'ts-expect-error': true, 'ts-nocheck': true, 'ts-check': false }],
      '@typescript-eslint/no-explicit-any': 'error',
      '@typescript-eslint/no-non-null-assertion': 'error',
      // `x as T` and `<T>x` anywhere, `as const` apart, except the few named sites: the one GraphQL boundary, where GitLab
      // has checked the answer against the schema the types came from, and the private constructor of each branded string
      // type (the brand is the whole point of the type: only that function may stamp it).
      'local/no-type-assertion': [
        'error',
        {
          allowed: {
            'hooks/decode.ts': { name: 'decodeGraphql', isExported: true },
            'hooks/markdown.ts': { name: 'brand', isExported: false },
            'hooks/model-text.ts': { name: 'brand', isExported: false },
            'hooks/svg.ts': { name: 'brand', isExported: false },
          },
        },
      ],
    },
  },
  {
    files: SOURCE,
    ignores: CORE,
    rules: {
      // JSON.parse answers `any`, which is a cast in disguise. Core files read JSON through `parseJson` in decode.ts, whose
      // `unknown` result must be checked before use; the type-aware rules below hold the core to that. Outside the core
      // nothing checks an `any`, so there the call itself is refused.
      'no-restricted-properties': [
        'error',
        { object: 'JSON', property: 'parse', message: 'JSON.parse answers `any`. Use `parseJson` from hooks/decode.ts and check what it returns.' },
      ],
    },
  },
  {
    files: ['hooks/**/*.{ts,tsx}'],
    rules: {
      'max-lines': ['error', { max: 400 }],
    },
  },
  // No module-level state, anywhere. A reload starts a module's variables over, a second session shares them and a test
  // cannot reset them; the pane's state belongs in atoms, which the engine saves, lists and redraws on. The one exception
  // is a module that holds what an atom cannot: a promise or a callback is not a value the engine can store, and a render
  // hook may not write one (the engine denies a write while drawing), so what waits across calls has nowhere else to be.
  {
    files: SOURCE,
    rules: {
      'local/no-module-state': [
        'error',
        {
          allowedModules: {
            'hooks/in-flight.ts': 'promises and callbacks cannot be stored in an atom, and the render hook cannot write one',
          },
        },
      ],
    },
  },
  // Only GitLab's own text may become Markdown to draw (it is what the Markdown view trusts as GitLab's), so `fromGitLab` is
  // reached from the one file that reads GitLab's answers; a test makes its text by reading an answer too.
  {
    files: SOURCE,
    rules: {
      'local/only-importers': [
        'error',
        {
          restricted: { fromGitLab: { allowed: ['hooks/gitlab.ts'], module: 'markdown', reason: "it stamps text as GitLab's, which only the reader of GitLab's answers can say" } },
        },
      ],
    },
  },
  {
    files: CORE,
    rules: {
      'no-restricted-imports': [
        'error',
        {
          patterns: [
            {
              group: ['claude-code', 'claude-code/*'],
              message: 'The core runs on plain data and imports nothing from the engine. Put engine code in a file outside the core.',
            },
            {
              // Relative imports must name a core file with its .ts extension (tools/gitlab_schema.ts runs gitlab-documents.ts under
              // plain Node, which needs it), or be the types contract. Anything else is not the core or is spelled wrong.
              regex: `^\\.{1,2}/(?!(?:(?:hooks|tests)/)?(?:${CORE_NAMES})\\.ts$|types$)`,
              message: 'The core imports only core files, each with its .ts extension, and ../types. If this module is pure, add it to tsconfig.core.json.',
            },
          ],
        },
      ],
    },
  },
  // Type-aware rules, the core against tsconfig.core.json and the rest of the source against tsconfig.json.
  {
    files: CORE,
    languageOptions: { parserOptions: { project: './tsconfig.core.json', tsconfigRootDir: __dirname } },
    rules: TYPE_AWARE,
  },
  {
    files: SOURCE,
    ignores: [...CORE, ...PROBE, ...TOOLS],
    languageOptions: { parserOptions: { project: './tsconfig.json', tsconfigRootDir: __dirname } },
    rules: TYPE_AWARE,
  },
  // The dev-only store probe is a plugin of its own with its own tsconfig, so the shipped plugin's compile does not take it in.
  {
    files: PROBE,
    languageOptions: { parserOptions: { project: './tools/store-probe/tsconfig.json', tsconfigRootDir: __dirname } },
    rules: TYPE_AWARE,
  },
  // The dev tools are one-shot Node processes, not modules a reload restarts or a second session shares: the reasons for the
  // module-state rule do not apply, and their `main()` is what "runs as the module loads". Everything else holds for them.
  {
    files: TOOLS,
    rules: { 'local/no-module-state': 'off' },
  },
  // The dev tools: their own tsconfig, with Node's declarations and none of the engine's.
  {
    files: TOOLS,
    languageOptions: { parserOptions: { project: './tsconfig.tools.json', tsconfigRootDir: __dirname } },
    rules: TYPE_AWARE,
  },
]
