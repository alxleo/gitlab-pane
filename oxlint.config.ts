// The lint gate: `npm run lint` locally, in the commit hook and in CI, and tools/check_core.ts on a core file as it is edited.
// oxlint, with its type-aware rules run by tsgolint, which is built on TypeScript 7 (its version names the TypeScript inside,
// so renovate.json raises the two together). Each file is type-checked in the project of the nearest tsconfig.json: the
// root's for hooks/, tests/ and tools/screens/, tools/tsconfig.json for the dev tools, the store probe's own for the probe.
//
// Each rule is here to make the careless way of writing code the one that fails. There are no per-file allowlists and no
// disable comments: tools/check_files.ts refuses `oxlint-` and `eslint-` directives in any file, where no comment can switch
// the refusal off. A rule that is wrong changes here, with its reason beside it, and what it flags is fixed in the code. The
// exceptions below name one module or one function each, and say why.
import { defineConfig } from 'oxlint'

import { coreFiles } from './tools/core.ts'

// The core: files that run on plain data, listed once, in tsconfig.core.json's "include".
const CORE = coreFiles()

const SOURCE = ['**/*.{ts,tsx}']

export default defineConfig({
  // The `correctness` category runs: the rules oxlint holds to flag code that is wrong or useless (an unused import, a
  // string made of an object, a spread that splits a character), plus the rules named below. Nothing else is on by default.
  categories: { correctness: 'error' },
  plugins: ['eslint', 'typescript'],
  jsPlugins: ['./tools/lint_rules.ts'],
  // Generated by tools/gitlab_schema.ts and checked there (`types --check`); a rule on it would only be fought by the generator.
  ignorePatterns: ['hooks/gitlab.generated.ts'],
  options: {
    typeAware: true,
    denyWarnings: true,
    reportUnusedDisableDirectives: 'error',
    respectEslintDisableDirectives: false,
  },
  overrides: [
    {
      files: SOURCE,
      rules: {
        'typescript/ban-ts-comment': ['error', { 'ts-ignore': true, 'ts-expect-error': true, 'ts-nocheck': true, 'ts-check': false }],
        'typescript/no-explicit-any': 'error',
        'typescript/no-non-null-assertion': 'error',
        // `x as T` and `<T>x` anywhere, `as const` apart, except the few named sites: the one GraphQL boundary, where GitLab
        // has checked the answer against the schema the types came from, and the private constructor of each branded string
        // type (the brand is the whole point of the type: only that function may stamp it).
        'local/no-type-assertion': [
          'error',
          {
            allowed: {
              'hooks/decode.ts': { name: 'decodeGraphql', isExported: true },
              'hooks/markdown.ts': { name: 'brand', isExported: false },
              'hooks/model-text.ts': { name: 'brand', isExported: false },
              'hooks/svg.ts': { name: 'brand', isExported: false },
            },
          },
        ],
        // No module-level state, anywhere. A reload starts a module's variables over, a second session shares them and a
        // test cannot reset them; the pane's state belongs in atoms, which the engine saves, lists and redraws on. The one
        // exception is a module that holds what an atom cannot: a promise or a callback is not a value the engine can store,
        // and a render hook may not write one (the engine denies a write while drawing), so what waits across calls has
        // nowhere else to be.
        'local/no-module-state': [
          'error',
          { allowedModules: { 'hooks/in-flight.ts': 'promises and callbacks cannot be stored in an atom, and the render hook cannot write one' } },
        ],
        // Only GitLab's own text may become Markdown to draw (it is what the Markdown view trusts as GitLab's), so
        // `fromGitLab` is reached from the one file that reads GitLab's answers; a test makes its text by reading an answer too.
        'local/only-importers': [
          'error',
          {
            restricted: {
              fromGitLab: { allowed: ['hooks/gitlab.ts'], module: 'markdown', reason: "it stamps text as GitLab's, which only the reader of GitLab's answers can say" },
            },
          },
        ],
        // The core imports core files by their .ts path, the types contract, and nothing of the engine. The rule reads the
        // core from tsconfig.core.json and leaves every other file alone.
        'local/core-imports': 'error',
        // The type-aware rules.
        'typescript/switch-exhaustiveness-check': 'error',
        'typescript/no-floating-promises': 'error',
        'typescript/no-unnecessary-condition': 'error',
        // A string, a number or a nullable one is not a condition: `''` and `0` are values, and `if (count)` is where a count
        // of zero goes missing. Say what is meant: `!== ''`, `> 0`, `!== null`.
        'typescript/strict-boolean-expressions': [
          'error',
          {
            allowString: false,
            allowNumber: false,
            allowNullableObject: false,
            allowNullableBoolean: false,
            allowNullableString: false,
            allowNullableNumber: false,
            allowNullableEnum: false,
            allowAny: false,
          },
        ],
        'typescript/no-unsafe-assignment': 'error',
        'typescript/no-unsafe-call': 'error',
        'typescript/no-unsafe-member-access': 'error',
        'typescript/no-unsafe-return': 'error',
        'typescript/no-unsafe-argument': 'error',
        'typescript/prefer-readonly': 'error',
      },
    },
    {
      // JSON.parse answers `any`, which is a cast in disguise. Core files read JSON through `parseJson` in decode.ts, whose
      // `unknown` result must be checked before use; the type-aware rules hold the core to that. Outside the core nothing
      // checks an `any`, so there the call itself is refused.
      files: SOURCE,
      excludeFiles: CORE,
      rules: {
        'no-restricted-properties': [
          'error',
          { object: 'JSON', property: 'parse', message: 'JSON.parse answers `any`. Use `parseJson` from hooks/decode.ts and check what it returns.' },
        ],
      },
    },
    {
      files: ['hooks/**/*.{ts,tsx}'],
      rules: { 'max-lines': ['error', { max: 400 }] },
    },
    {
      // The dev tools are one-shot Node processes, not modules a reload restarts or a second session shares: the reasons for
      // the module-state rule do not apply, and their `main()` is what "runs as the module loads". Everything else holds.
      files: ['tools/*.ts'],
      rules: { 'local/no-module-state': 'off' },
    },
  ],
})
